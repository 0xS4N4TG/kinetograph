// Generates the launch film's voiceover with OpenAI TTS (gpt-4o-mini-tts) into public/vo/*.wav and writes
// sound-vo.ts (line durations) beside the soundtrack. The key is read from ~/.openai_key, never printed.
//   node tools/vo.mjs [--voice onyx|ash|...] [--only 03,04] [--out dir] [--engine openai|say]
// --engine say is the offline stopgap (macOS `say`, voice Daniel, EQ'd lower) for when the OpenAI account has no credit.
import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : fallback; };
const voice = opt('voice', 'onyx');
const only = opt('only', '') ? opt('only', '').split(',') : null;
const engine = opt('engine', 'openai');
const outDir = opt('out', join(here, '..', 'public', 'vo'));

const INSTRUCTIONS =
  'A deep, low, unhurried adult male voice. Calm and confident, like the narrator of a restrained film-launch trailer. ' +
  'Speak close to the microphone with a warm low register, short pauses at full stops, no sales energy, no smile, no rush. ' +
  'Land each short phrase and let it end downward.';

/** [file, text, say rate override]. Placement (shot and offset) lives in sound.tsx. */
export const LINES = [
  ['01-how', 'how.'],
  ['02-question', 'do you make a video without a browser?'],
  ['03-screenshot', 'every frame. a screenshot.'],
  ['04-you-dont', 'you don’t.'],
  ['05-render', 'you just render it.'],
  ['07-your', 'your demo. your launch. your changelog. videos that render for you.'],
  ['08-remotion', 'your remotion code. drop-in. ninety-eight percent of the API.'],
  ['09-numbers', 'same project. same frames. seven times faster.'],
  ['10-pixels', 'no chrome. no screenshots. just pixels.', 250],
  ['12-end', 'kinetograph. write remotion. render native.'],
];

const key = engine === 'openai' ? readFileSync(join(homedir(), '.openai_key'), 'utf8').trim() : '';
mkdirSync(outDir, { recursive: true });

function wavSeconds(buf) {
  // walk RIFF chunks for fmt and data
  let rate = 24000, ch = 1, bits = 16, pos = 12;
  while (pos + 8 <= buf.length) {
    const id = buf.toString('ascii', pos, pos + 4);
    let size = buf.readUInt32LE(pos + 4);
    if (id === 'fmt ') { ch = buf.readUInt16LE(pos + 10); rate = buf.readUInt32LE(pos + 12); bits = buf.readUInt16LE(pos + 22); }
    if (id === 'data') { if (size === 0xffffffff || pos + 8 + size > buf.length) size = buf.length - pos - 8; return size / (rate * ch * (bits / 8)); }
    pos += 8 + size;
  }
  return 0;
}

const durations = {};
for (const [name, text, lineRate] of LINES) {
  const file = join(outDir, `${name}.wav`);
  if (only && !only.some((o) => name.startsWith(o))) {
    if (existsSync(file)) durations[name] = wavSeconds(readFileSync(file));
    continue;
  }
  if (engine === 'say') {
    const tmp = join(outDir, `${name}.aiff`);
    execFileSync('say', ['-v', opt('voice', 'Daniel'), '-r', opt('rate', String(lineRate ?? 215)), '-o', tmp, text.replace(/\. /g, '. [[slnc 150]] ')]);
    // a lower, closer voice: -1.8 semitones by resampling (also slows it), low shelf up, high roll-off
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', tmp, '-af',
      'aresample=44100,asetrate=44100*0.9,aresample=44100,lowshelf=g=5:f=180,highpass=f=70,lowpass=f=9000,loudnorm=I=-18:TP=-2',
      '-ar', '24000', '-ac', '1', file]);
    rmSync(tmp);
    durations[name] = wavSeconds(readFileSync(file));
    console.log(name, durations[name].toFixed(2), 's');
    continue;
  }
  const res = await fetch('https://api.openai.com/v1/audio/speech', {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model: 'gpt-4o-mini-tts', voice, input: text, instructions: INSTRUCTIONS, response_format: 'wav' }),
  });
  if (!res.ok) { console.error(name, res.status, (await res.text()).slice(0, 200)); process.exit(1); }
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(file, buf);
  durations[name] = wavSeconds(buf);
  console.log(name, durations[name].toFixed(2), 's');
}

if (outDir === join(here, '..', 'public', 'vo')) {
  const body = Object.entries(durations).map(([n, d]) => `  '${n}': ${d.toFixed(3)},`).join('\n');
  writeFileSync(join(here, '..', 'sound-vo.ts'), `// Generated by tools/vo.mjs: seconds of each voiceover line.\nexport const VO_SECONDS: Record<string, number> = {\n${body}\n};\n`);
}
